#!/usr/bin/env python3
"""Writes port/machine/engine/src/transmitter_model.rs from Mekanism's transmitter OBJ models.

    python3 port/gen_transmitter_model.py upstream

The output is generated data from upstream's MIT-licensed models. It holds each named group's quads:
corners in blocks, and a UV rectangle in 16ths, so `native_draw_quad` can draw them.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "machine/engine/src/transmitter_model.rs"
SMALL = "src/main/resources/assets/mekanism/models/block/transmitter_small.obj.mek"
CONTENTS = "src/main/resources/assets/mekanism/models/transmitter_contents.obj"
CENTRE = ("CentreMaterialDown", "CentreMaterialUp", "CentreMaterialNorth", "CentreMaterialSouth",
          "CentreMaterialWest", "CentreMaterialEast")
UV_SCALE = 16.0


def parse(path: Path) -> dict[str, list[tuple[str, list]]]:
    vertices, uvs, groups, group, material = [], [], {}, None, ""
    for line in path.read_text().splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "v":
            vertices.append(tuple(float(part) for part in parts[1:4]))
        elif parts[0] == "vt":
            uvs.append(tuple(float(part) for part in parts[1:3]))
        elif parts[0] in ("o", "g"):
            group = parts[1]
            groups.setdefault(group, [])
        elif parts[0] == "usemtl":
            material = parts[1]
        elif parts[0] == "f":
            corners = [part.split("/") for part in parts[1:]]
            if len(corners) != 4:
                raise SystemExit(f"{path}: a face that isn't a quad in {group}")
            quad = [(vertices[int(c[0]) - 1], uvs[int(c[1]) - 1]) for c in corners]
            groups[group].append((material, quad))
    return groups


def rect_quad(quad: list) -> tuple[list, list]:
    """Orders a quad so its UVs run u0 v0, u0 v1, u1 v1, u1 v0, with `flip_v`, as native_draw_quad needs."""
    flipped = [(corner, (uv[0], 1.0 - uv[1])) for corner, uv in quad]
    for start in range(4):
        turned = flipped[start:] + flipped[:start]
        (a, b, c, d) = [uv for _, uv in turned]
        if a[0] == b[0] and c[0] == d[0] and a[1] == d[1] and b[1] == c[1]:
            return [corner for corner, _ in turned], [a[0], a[1], c[0], c[1]]
    raise SystemExit(f"a quad's UVs are not a rectangle: {quad}")


def literal(values) -> str:
    return "[" + ", ".join(f"{value:.6f}" for value in values) + "]"


def rust_group(name: str, quads: list, is_centre, offset: float) -> str:
    rows = []
    for material, quad in quads:
        corners, uv = rect_quad(quad)
        corners = [[axis + offset for axis in corner] for corner in corners]
        points = ", ".join(literal(corner) for corner in corners)
        scaled = literal(value * UV_SCALE for value in uv)
        rows.append(f"            Face {{ centre: {str(is_centre(material)).lower()}, corners: [{points}], uv: {scaled} }},")
    body = "\n".join(rows)
    return f'    Group {{\n        name: "{name}",\n        faces: &[\n{body}\n        ],\n    }},'


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    upstream = Path(sys.argv[1])
    small = parse(upstream / SMALL)
    contents = parse(upstream / CONTENTS)
    wanted = [(name, faces) for name, faces in small.items() if name.endswith(("NONE", "NORMAL"))]
    wanted_contents = [(name, faces) for name, faces in contents.items() if name.endswith(("NONE", "NORMAL"))]
    print(f"{len(wanted)} of {len(small)} groups, {len(wanted_contents)} of {len(contents)} contents groups")
    out = [
        "//! Generated by port/gen_transmitter_model.py from Mekanism's transmitter models (MIT). Don't edit.",
        "",
        "#[derive(Debug)]",
        "pub struct Face {",
        "    /// Drawn with a `#center_*` texture, or `#side`.",
        "    pub centre: bool,",
        "    /// In blocks, from the block's lower north-west corner.",
        "    pub corners: [[f32; 3]; 4],",
        "    /// u0, v0, u1, v1 in 16ths of the texture.",
        "    pub uv: [f32; 4],",
        "}",
        "",
        "#[derive(Debug)]",
        "pub struct Group {",
        "    pub name: &'static str,",
        "    pub faces: &'static [Face],",
        "}",
        "",
        "/// `transmitter_small.obj.mek`, without the pull and push modes.",
        "pub const SMALL: &[Group] = &[",
    ]
    out += [rust_group(name, faces, lambda m: m in CENTRE, 0.0) for name, faces in wanted]
    out += ["];", "", "/// `transmitter_contents.obj`, centred on the block's middle in the real mod.", "pub const CONTENTS: &[Group] = &["]
    out += [rust_group(name, faces, lambda m: False, 0.5) for name, faces in wanted_contents]
    out += ["];", ""]
    OUT.write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
